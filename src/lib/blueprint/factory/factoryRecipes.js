/** 配方数据；查不到返回 null */
function recipeData(recipeId) {
  return RECIPE_DATA[recipeId] ?? null;
}

/** 配方名；查不到返回空串 */
function recipeName(recipeId) {
  return RECIPE_DATA[recipeId]?.name ?? '';
}

/** 配方类型（ERecipeType 的数值） */
function recipeType(recipeId) {
  return RECIPE_DATA[recipeId]?.type ?? 0;
}

/** 配方耗时（游戏 tick）；查不到返回 0 */
function recipeTime(recipeId) {
  return RECIPE_DATA[recipeId]?.time ?? 0;
}

/** 配方在选择窗里的页（1 物品 / 2 建筑）；查不到返回 0 */
function recipePage(recipeId) {
  return RECIPE_PAGES[recipeId] ?? 0;
}

/** 配方主产物物品 id；查不到（或没有产物）返回 0 */
function recipeProduct(recipeId) {
  return RECIPE_DATA[recipeId]?.out[0]?.id ?? 0;
}

/** 这配方能不能吃增产效果（不能的只能加速） */
function recipeProductive(recipeId) {
  return RECIPE_DATA[recipeId]?.productive ?? true;
}

/** 这类配方里都有哪些配方 id；类型不认识给空数组 */
function recipeIdsOfType(typeId) {
  return RECIPE_TYPES[typeId]?.recipes ?? [];
}

/** 这栋建筑能跑哪类配方 */
function recipeTypeOfBuilding(itemId) {
  for (const [typeId, info] of Object.entries(RECIPE_TYPES)) {
    if (info.buildings.includes(itemId)) return Number(typeId);
  }
  return 0;
}

